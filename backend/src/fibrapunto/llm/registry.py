"""Model roles and the registry (§10, §14.2).

    "The choice of reasoning model is the operator's, not the builder's, and the
    design keeps it reversible: instructions, capability contracts and scope
    statements are written to be independent of any particular model."

Nothing in this codebase names a model. Code asks for a *role*; the registry
resolves the role to a pinned model id from configuration. Swapping the agent's
model is an edit to `.env`, which is what makes §10's reversibility claim
demonstrable rather than rhetorical.

Two rules are enforced here rather than trusted:

  * **Judge ≠ subject.** §10: "The model that grades the evaluation transcripts
    must not be the model that produced them. Grading one's own output is not
    measurement." Checked at vendor level, not model-id level — two checkpoints
    of one family share failure modes, and a judge that hallucinates in the same
    places as the subject will agree with it enthusiastically.

  * **The pin is verified, not assumed.** OpenRouter offers no native pinning
    guarantee; under load it may route elsewhere. `allow_fallbacks: false` asks
    it not to, and `assert_served_model` checks that it didn't. A "pinned" eval
    run that silently changed model is worse than no pin at all.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date
from enum import StrEnum
from functools import lru_cache
from typing import Any

from fibrapunto.settings import get_settings


class ModelRole(StrEnum):
    agent = "agent"
    """Answers the customer. The model whose behaviour §1 measures."""

    router = "router"
    """Classifies the turn into a domain (§4). Cheap and fast; runs every turn."""

    judge = "judge"
    """Grades transcripts (§14.2). Must not be the agent, or its vendor."""

    persona = "persona"
    """Generates test-set variants (§14.1's "10 variants generated by a language
    model other than the agent's")."""


class ModelPinViolation(RuntimeError):
    """OpenRouter served a model other than the one requested."""


class JudgeIsSubject(RuntimeError):
    """The evaluation would be grading its own output."""


@dataclass(frozen=True, slots=True)
class ModelSpec:
    role: ModelRole
    id: str
    pinned_on: date
    max_tokens: int

    @property
    def vendor(self) -> str:
        """The part before the slash — `anthropic`, `google`, `openai`."""
        return self.id.split("/", 1)[0]


# Output budget per role. Set explicitly, and not only for tidiness:
#
#   * OpenRouter reserves credit against `max_tokens`, not against what a
#     request actually uses. Omitting it means the client sends the model's
#     ceiling (64k+), and the request is refused with a 402 unless the balance
#     covers 64k output tokens — for a reply that will use fifty. See
#     docs/FRICTION-LOG.md entry 3.
#
#   * §16 makes cost per conversation a stated criterion. A budget nobody set
#     is a budget nobody can defend.
#
# The numbers come from the spec's own worked examples: §4.1's replies are
# roughly eighty words each. These are generous against that, not tight.
MAX_TOKENS = {
    ModelRole.agent: 1024,  # a customer reply, possibly with a tool call
    ModelRole.router: 256,  # a small JSON object: domain, confidence, sentiment
    ModelRole.judge: 1024,  # the §14.2 schema, including a rationale
    ModelRole.persona: 512,  # one customer turn
}


class LLMRegistry:
    def __init__(self, specs: dict[ModelRole, ModelSpec]) -> None:
        self._specs = specs
        self.validate()

    def __getitem__(self, role: ModelRole) -> ModelSpec:
        return self._specs[role]

    def validate(self) -> None:
        """Run at construction. Refuses to start rather than producing a
        measurement nobody should trust."""
        agent = self._specs[ModelRole.agent]
        judge = self._specs[ModelRole.judge]

        if agent.id == judge.id:
            raise JudgeIsSubject(
                f"The judge and the agent are the same model ({agent.id}). "
                f"§10: grading one's own output is not measurement."
            )

        if agent.vendor == judge.vendor:
            raise JudgeIsSubject(
                f"The judge ({judge.id}) and the agent ({agent.id}) share a "
                f"vendor ({agent.vendor}). Two checkpoints of one family share "
                f"failure modes: a judge that errs where the subject errs will "
                f"agree with it. Choose a judge from another vendor."
            )

    def provider_options(self) -> dict[str, Any]:
        """The OpenRouter routing block. Not tuning knobs — both entries are
        load-bearing.

        `allow_fallbacks: false` is what makes §10's version pinning mean
        anything. `data_collection: "deny"` restricts routing to providers that
        do not retain prompts, which is a §9 control rather than a README
        promise.

        `usage.include` asks the provider to report what each call cost, in
        its own accounting, on the response. §16 makes cost per conversation a
        stated criterion; this is what turns it from an assertion into a number
        on the trace (llm/chat.py, `CostLedger`).
        """
        return {
            "provider": {
                "allow_fallbacks": False,
                "data_collection": "deny",
            },
            "usage": {"include": True},
        }

    @staticmethod
    def assert_served_model(requested: str, served: str | None) -> None:
        """§10 demands pinning "with notice of change". The provider gives
        neither, so we manufacture both: compare every response against what was
        asked for, and fail loudly.

        One tolerance, and only one: a dated snapshot of the requested id
        (`…-20260801`, `…-2026-08-01`). A provider may report the concrete
        snapshot an alias resolved to; that is the same model, and the served
        id is recorded on the conversation, so a change is still visible.
        Anything else — another model, another size, another vendor — fails.
        """
        if served is None:
            raise ModelPinViolation(
                f"The provider did not report which model served the request "
                f"(asked for {requested}). The pin cannot be verified."
            )
        snapshot = re.fullmatch(
            rf"{re.escape(requested)}-(?:\d{{8}}|\d{{4}}-\d{{2}}-\d{{2}})", served
        )
        if served != requested and not snapshot:
            raise ModelPinViolation(
                f"Asked for {requested}, was served {served}. "
                f"allow_fallbacks is false, so this should not happen."
            )


@lru_cache
def get_registry() -> LLMRegistry:
    settings = get_settings()
    # The date each pin was last reviewed. §10 treats a version change as a
    # change to the system: the evaluation suite is re-run before it reaches
    # anyone, and this field is the prompt to ask whether that happened.
    pinned_on = date(2026, 9, 22)
    configured = {
        ModelRole.agent: settings.model_agent,
        ModelRole.router: settings.model_router,
        ModelRole.judge: settings.model_judge,
        ModelRole.persona: settings.model_persona,
    }
    return LLMRegistry(
        {
            role: ModelSpec(role, model_id, pinned_on, MAX_TOKENS[role])
            for role, model_id in configured.items()
        }
    )
